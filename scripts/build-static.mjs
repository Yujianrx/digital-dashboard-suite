import {cp,readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {spawnSync,execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {dirname} from 'node:path';
const root=new URL('../',import.meta.url);
for(const file of ['check-public.mjs','build-operations.mjs']) {
  const result=spawnSync(process.execPath,[fileURLToPath(new URL(file,import.meta.url))],{cwd:fileURLToPath(root),stdio:'inherit'});
  if(result.status!==0)process.exit(result.status||1);
}
const target=new URL('dist/static/',root);
await rm(target,{recursive:true,force:true});await mkdir(target,{recursive:true});
// Publish only source files visible to Git plus files generated by this Vite build.
// Ignored imports, private JSON, uploads and runtime data never enter the artifact.
const sources=execFileSync('git',['-c','core.excludesFile=','ls-files','--cached','--others','--exclude-standard','-z','--','app/offline-package','operations/public'],{cwd:fileURLToPath(root),encoding:'utf8'}).split('\0').filter(Boolean);
const files=new Map();
for(const source of sources) {
  if(source.startsWith('app/offline-package/'))files.set(source.slice('app/offline-package/'.length),source);
  else if(source.startsWith('operations/public/'))files.set('operations/'+source.slice('operations/public/'.length),'app/offline-package/operations/'+source.slice('operations/public/'.length));
}
const manifest=JSON.parse(await readFile(new URL('operations/dist/.vite/manifest.json',root),'utf8'));
files.set('operations/index.html','app/offline-package/operations/index.html');
for(const chunk of Object.values(manifest)) for(const path of [chunk.file,...(chunk.css||[]),...(chunk.assets||[])])files.set('operations/'+path,'app/offline-package/operations/'+path);
for(const [destination,source] of files) {
  if(destination.split('/').some(p=>p==='..'||p.startsWith('.')) || /(?:^|\/)(?:private|uploads|backups|logs)(?:\/|$)|\.(?:private|local)\.json$|\.(?:db|sqlite|log|zip)$/.test(destination))throw Error('Non-public artifact file: '+destination);
  const output=new URL(destination,target);await mkdir(dirname(fileURLToPath(output)),{recursive:true});await cp(new URL(source,root),output);
}
const seed=JSON.parse(await readFile(new URL('server/initial-state.json',root),'utf8'));
await writeFile(new URL('runtime-config.js',target),`window.DashboardRuntime={mode:'static',storage:'browser',basePath:new URL('.',document.currentScript.src).pathname,seed:${JSON.stringify(seed).replace(/</g,'\\u003c')}};\n`);
await writeFile(new URL('.nojekyll',target),'');
console.log('Static artifact: dist/static (empty seed; browser-only persistence).');
